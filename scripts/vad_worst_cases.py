"""List the worst sessions of each dataset's VAD audit with the evidence for their flagged regions.

For each audited dataset: the sessions with the most unannotated speech and the most silent reference speech
(Silero with the 30 s state reset, primary reference), each with its longest flagged regions, the other
witnesses' coverage, the level above the noise floor, word-timing coverage and, where the Whisper check
transcribed the region, Whisper's text.

Usage: python scripts/vad_worst_cases.py [--sessions 3] [--out results/vad/worst_cases.md]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V = ROOT / "results" / "vad"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sessions", type=int, default=3)
    ap.add_argument("--vad", default="silero_x2")
    ap.add_argument("--out", default=str(V / "worst_cases.md"))
    a = ap.parse_args()
    lines = ["# Worst sessions of the VAD audit, with evidence", "",
             f"Detector: {a.vad}; primary reference. Columns: region (s), duration, level above the session noise floor "
             "(dB), coverage by the reference / Nemotron / energy / WebRTC / word timings, mean Silero probability "
             "(stock / reset), Whisper text when the region was in the Whisper check (`[speech]` = passes the "
             "intelligible-speech test). Generated by `scripts/vad_worst_cases.py`.", ""]
    for p in sorted((V / "audit").glob("audit.*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        wp = V / "whisper" / f"whisper.{r['dataset']}.{r['view']}.json"
        wh = {}
        if wp.exists():
            for x in json.loads(wp.read_text(encoding="utf-8"))["regions"]:
                wh[(x["session_id"], round(x["start"], 2))] = x
        lines += [f"## {r['dataset']} ({r['view']})", ""]
        for kind, key, label in (("unref", "worst_unref", "unannotated speech"),
                                 ("unvoiced", "worst_unvoiced", "silent reference speech")):
            worst = r["summary"]["primary"][a.vad][key][: a.sessions]
            lines.append(f"**Most {label}** (% of the session's reference speech): "
                         + ", ".join(f"{sid} ({v}%)" for sid, v in worst))
            lines.append("")
            per = {x["session_id"]: x for x in r["per_session"]}
            for sid, _ in worst:
                regs = per[sid]["refs"]["primary"][a.vad].get(f"top_{kind}", [])[:3]
                for e in regs:
                    w = wh.get((sid, round(e["start"], 2)))
                    wtxt = f" Whisper: \"{w['whisper'][:100]}\"{' [speech]' if w['speech'] else ''}" if w else ""
                    lines.append(
                        f"- {sid} {e['start']:.1f}-{e['end']:.1f} ({e['dur']:.1f} s): level {e.get('level_db_above_floor')} dB, "
                        f"ref {e.get('ref_cov')}, nemotron {e.get('nemotron_cov', '-')}, energy {e.get('energy_cov', '-')}, "
                        f"webrtc {e.get('webrtc_cov', '-')}, words {e.get('words_cov', '-')}, p(silero) "
                        f"{e.get('silero_stock_mean_prob')}/{e.get('silero_r30_mean_prob')}.{wtxt}")
            lines.append("")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
